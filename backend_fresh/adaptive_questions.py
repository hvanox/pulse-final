def get_adaptive_question(user_id: str, topic: str, difficulty: int, exclude_ids: list = None):
    """Выбрать вопрос по теме и сложности, исключая уже отвеченные."""
    exclude_ids = exclude_ids or []
    candidates = [q for q in ADAPTIVE_QUESTIONS
                  if q["topic"] == topic and q["difficulty"] == difficulty and q["id"] not in exclude_ids]
    if not candidates:
        # Fallback: любой вопрос по теме
        candidates = [q for q in ADAPTIVE_QUESTIONS if q["topic"] == topic and q["id"] not in exclude_ids]
    if not candidates:
        # All answered — reset
        candidates = [q for q in ADAPTIVE_QUESTIONS if q["topic"] == topic]
    if not candidates:
        return None
    # Deterministic but varied selection
    seed = int(hashlib.md5(f"{user_id}:{topic}:{len(exclude_ids)}".encode()).hexdigest()[:8], 16)
    return candidates[seed % len(candidates)]


def get_questions_for_lesson(user_id: str, topic: str, mastery: float, count: int = 3, exclude_ids: list = None):
    """Получить набор вопросов для урока, адаптированных по сложности."""
    exclude_ids = exclude_ids or []
    # Определяем сложность по mastery
    if mastery < 0.4:
        difficulties = [1, 1, 2]  # Больше лёгких
    elif mastery < 0.7:
        difficulties = [1, 2, 2]  # Средний микс
    else:
        difficulties = [2, 3, 3]  # Больше сложных

    questions = []
    used_ids = list(exclude_ids)
    for diff in difficulties[:count]:
        q = get_adaptive_question(user_id, topic, diff, used_ids)
        if q:
            questions.append(q)
            used_ids.append(q["id"])
    return questions
